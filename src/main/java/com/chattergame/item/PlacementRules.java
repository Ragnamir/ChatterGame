package com.chattergame.item;

/**
 * Вместимость: какой предмет помещается в какое хранилище (`REQUIREMENTS §10`, `D-111`).
 *
 * <p>Правило действует ровно на два хранилища персонажа: мелкое принимает только мелкое,
 * крупное — только крупное. На `LOCATION` и `CHEST` размер не влияет, раскладка там на
 * усмотрение мастера; мастер не ограничен и в хранилищах персонажа (`D-015`).
 *
 * <p>Ограничение адресовано игроку и включается вместе с занятостью (`E13`, `D-109`), но
 * живёт здесь уже сейчас: правило, написанное только на будущее и ни разу не исполненное,
 * к `E13` успевает разойтись с кодом, поэтому его проверяет тест этапа.
 */
public final class PlacementRules {

    private PlacementRules() {
    }

    /** Помещается ли предмет размера {@code size} в хранилище типа {@code kind}. */
    public static boolean fits(StorageKind kind, ItemSize size) {
        if (!kind.belongsToCharacter()) {
            return true;
        }
        return kind.isSmall() == (size == ItemSize.SMALL);
    }
}
