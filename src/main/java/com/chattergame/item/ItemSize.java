package com.chattergame.item;

/**
 * Размер предмета (`REQUIREMENTS §10`, `D-017`). Крупный предмет виден всем, кто видит
 * персонажа, мелкий — нет; от размера зависит и то, в какое из двух хранилищ персонажа
 * предмет помещается (`D-111`).
 *
 * <p>На локационные хранилища и на действия мастера размер не влияет: там раскладка на
 * усмотрение мастера, а `D-015` снимает с него ограничения.
 */
public enum ItemSize {
    SMALL,
    LARGE
}
