package com.chattergame.item;

/**
 * Тип хранилища (`REQUIREMENTS §10`, `D-016`). Словарь объявлен целиком, потому что значение
 * колонки `storage.kind` — это данные, которые уже пишет и читает БД: частичное перечисление
 * уронило бы чтение на первой же строке чужого типа.
 *
 * <p>Тип задаёт правило видимости содержимого, а не отдельная проверка в запросе: «кто видит
 * содержимое» формулируется один раз здесь (`D-016`).
 */
public enum StorageKind {

    /** Хранилище локации: содержимое видно всем присутствующим (`REQUIREMENTS §10`). */
    LOCATION,

    /** Сундук: описание видно присутствующим, содержимое — после открытия мастером. */
    CHEST,

    /** Мелкое хранилище персонажа: только владельцу и мастеру. */
    CHARACTER_HIDDEN,

    /** Крупное хранилище персонажа: всем, кому виден владелец (`D-019`). */
    CHARACTER_VISIBLE;

    /** Хранилище персонажа — одно из двух; локационное привязано к чату, а не к персонажу. */
    public boolean belongsToCharacter() {
        return this == CHARACTER_HIDDEN || this == CHARACTER_VISIBLE;
    }

    /** Мелкое хранилище персонажа вмещает только мелкие предметы (`D-111`). */
    public boolean isSmall() {
        return this == CHARACTER_HIDDEN;
    }
}
