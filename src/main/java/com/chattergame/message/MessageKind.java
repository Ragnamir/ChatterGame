package com.chattergame.message;

/**
 * Пять типов сообщений (`D-031`). Словарь закрыт решением, а не местом вызова: тип —
 * это часть контракта (он же `messageKind` в `contract/events.schema.json`), и строка
 * на месте вызова не проверялась бы компилятором.
 *
 * <p>От чьего имени пишется сообщение, решает тип, а не поле `character_id`: `SPEECH`,
 * `ACTION` и сообщение мастера от лица персонажа идут от персонажа, `JOKE` — от участия
 * (`D-099`), `MASTER` — от мастера, `SYSTEM` генерирует система и не пишет никто.
 */
public enum MessageKind {

    /** Речь персонажа. Расходует бюджет хода персонажа (`REQUIREMENTS §11`). */
    SPEECH,

    /** Описание действия. Расходует бюджет хода персонажа. */
    ACTION,

    /** Шутка: метагейм игрока, присутствие не требуется (`D-099`). */
    JOKE,

    /** Событие мира от мастера, не от персонажа. */
    MASTER,

    /** Проекция журнала: вход, выход, правки, переходы, выдача, запрет, ход (`D-031`). */
    SYSTEM
}
