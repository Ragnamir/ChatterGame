package com.chattergame.message;

/**
 * Вид субъекта получения (`D-086`). Строка за строкой это то же, что `subject_kind`
 * в `inbox_entry` и `read_cursor`.
 *
 * <p>Игровой контент адресуется персонажу: его читает тот, кто за персонажа играет.
 * Открытый контент и всё, что адресовано игроку как человеку, адресуется участию —
 * у наблюдателя персонажа нет вовсе (`D-063`), а шутка пишется от участия (`D-099`).
 * Read-путь для обоих случаев один, иначе `D-030` обходится отдельным фильтром.
 */
public enum SubjectKind {
    CHARACTER,
    MEMBERSHIP
}
