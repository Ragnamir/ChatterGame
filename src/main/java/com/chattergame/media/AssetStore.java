package com.chattergame.media;

/**
 * Хранилище содержимого ассетов. Абстракция названа в `REQUIREMENTS §19` и существует
 * ровно ради одной замены: файловая система сегодня, объектное хранилище при переезде.
 * Больше в этом интерфейсе нет ничего — ни прав, ни квот, ни метаданных: это учёт
 * `asset`, а не хранилище.
 *
 * <p>Ключ задаёт вызывающий и он же хранится в `asset.storage_key`. Запись обязана быть
 * атомарной: частично записанный файл не должен стать виден под своим ключом
 * (`D-077` — иначе упавшая загрузка оставит битую картинку вместо прежней).
 */
public interface AssetStore {

    void write(String key, byte[] content);

    byte[] read(String key);

    boolean exists(String key);

    void delete(String key);
}
