package com.chattergame.notification;

/**
 * Канал доставки уведомления (`PLAN` O03, `D-070`, `D-148`).
 *
 * <p>Канал — сохранённое намерение, а не обещание доставки: на `O03` существует только
 * сухой прогон, и ни один транспорт не подключён. Значение говорит, куда уведомление
 * пошло бы, когда транспорт появится.
 *
 * <p>Push в словаре нет, пока `D-070` отложен: значение, которое нельзя выбрать осмысленно,
 * превратило бы настройку в ложь — человек включил бы то, чего нет.
 */
public enum NotificationChannel {

    /** Не беспокоить: событие проходит фильтр, но адресату не назначается. */
    NONE,

    /** Отметка внутри приложения. */
    IN_APP,

    /** Письмо на подтверждённый адрес. */
    EMAIL
}
