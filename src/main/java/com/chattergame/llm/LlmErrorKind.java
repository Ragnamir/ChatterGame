package com.chattergame.llm;

/**
 * Классы отказа провайдера (`D-043`). Отказ модели — штатное состояние, а не исключение:
 * лимит, таймаут и невалидный ответ лечатся по-разному, поэтому мастер обязан видеть,
 * что именно случилось, а не общее «модель не ответила».
 *
 * <p>Код уходит в `request.error` и переводится клиентом по ключу интернализации: текст
 * провайдера нестабилен и в контракт не входит. Классы намеренно не сливаются: «кончились
 * лимиты» — это ожидание или смена ключа, «таймаут» — повтор, «невалидный ответ» — правка
 * промпта.
 */
public enum LlmErrorKind {

    /** Провайдер ответил `429`: квота или частота запросов исчерпаны. */
    RATE_LIMIT("llm_rate_limited"),

    /** Ответ не пришёл за отведённое время. */
    TIMEOUT("llm_timeout"),

    /** Ответ пришёл, но это не JSON нужной формы. */
    INVALID_RESPONSE("llm_invalid_response"),

    /** Провайдер ответил ошибкой или недоступен. */
    PROVIDER_ERROR("llm_provider_error"),

    /** Ключ отвергнут провайдером (`401`/`403`): ключ неверен или отозван. */
    AUTH_FAILED("llm_auth_failed"),

    /** У мастера нет активного ключа: опции LLM недоступны целиком (`D-042`). */
    NOT_CONFIGURED("llm_not_configured");

    private final String code;

    LlmErrorKind(String code) {
        this.code = code;
    }

    public String code() {
        return code;
    }
}
