package com.chattergame.turn;

import java.util.UUID;

/**
 * Израсходованный бюджет хода (`REQUIREMENTS §14`): одна строка на пару «ход + персонаж»,
 * потому что лимит суммарный по всем чатам, кроме личного (`D-013`).
 *
 * <p>Оба флага независимы: речь и действие — разные лимиты, и «потратил речь» не мешает
 * действию. Строка создаётся лениво, при первом расходе: персонажей в игре к моменту
 * открытия хода может ещё не быть, а появившиеся среди хода должны получить свой бюджет
 * без отдельного шага мастера.
 */
public record TurnBudget(
        UUID id,
        UUID characterId,
        boolean actionUsed,
        boolean speechUsed) {
}
