package com.chattergame.request;

/**
 * Статус операции заявки. Отдельный словарь, а не статус заявки: `D-041` требует частичного
 * одобрения по операциям, и «заявка одобрена» не означает, что применились все её строки.
 *
 * <p>`ROLLED_BACK` — не «отменена до применения», а «применена и возвращена»: откат
 * восстанавливает старое значение из журнала, оставляя и правку, и её отмену в истории.
 */
public enum OperationStatus {
    PENDING,
    APPLIED,
    REJECTED,
    FAILED,
    ROLLED_BACK
}
