package com.chattergame.request;

/**
 * Статус заявки (`REQUIREMENTS §17`). Перечисление фиксируется целиком, включая состояния
 * LLM-вызова (`RUNNING`, `FAILED`): словарь — контракт, и расширять его на следующем этапе
 * значило бы менять формат, который уже читают клиенты.
 *
 * <p>`PARTIALLY_APPROVED` — не «почти одобрено», а точный итог: часть операций применена,
 * часть отклонена. Отдельный статус нужен потому, что `D-041` требует частичного одобрения
 * по операциям, и «одобрено» скрыло бы, что часть правок не дошла.
 */
public enum RequestStatus {
    PENDING,
    RUNNING,
    SUCCEEDED,
    FAILED,
    APPROVED,
    REJECTED,
    PARTIALLY_APPROVED,
    EXPIRED;

    /**
     * Заявка ещё не решена: такие берёт автодекларация просрочки.
     *
     * <p>`SUCCEEDED` здесь не «одобрено», а «модель ответила, операции готовы» (`D-043`):
     * предложение LLM ждёт мастера ровно так же, как просьба игрока, и срок жизни у него
     * тот же. `RUNNING` входит потому, что вызов модели — ожидание, а не решение, но
     * решать по такой заявке нельзя: операции ещё не пришли ({@link #awaitingDecision()}).
     */
    public boolean open() {
        return this == PENDING || this == RUNNING || this == SUCCEEDED;
    }

    /** По заявке можно принять решение: операции известны, вызов модели уже не идёт. */
    public boolean awaitingDecision() {
        return this == PENDING || this == SUCCEEDED;
    }
}
