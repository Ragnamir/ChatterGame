package com.chattergame.chat;

/**
 * Состояние видимости ребра для конкретного персонажа (`REQUIREMENTS §8`).
 *
 * <p>Это одна ось, а не две: мастер «открывает и закрывает переходы» именно здесь, по
 * каждому персонажу отдельно, потому что и знание перехода привязано к персонажу. Ребро
 * может быть открыто одному персонажу и неизвестно другому, стоящему в той же локации.
 *
 * <p>{@link #UNKNOWN} хранится значением, а не отсутствием строки: забрать знание назад
 * мастер тоже может, а удаление строк запрещено (`D-010`, инвариант `physicalDeletions`).
 */
public enum EdgeState {

    /** Персонаж не знает, что переход существует; клиенту ребро не отдаётся. */
    UNKNOWN,

    /** Персонаж знает переход, но пройти нельзя; причина обязательна и показывается игроку. */
    KNOWN_UNAVAILABLE,

    /** Персонаж знает переход и может пройти. */
    AVAILABLE
}
