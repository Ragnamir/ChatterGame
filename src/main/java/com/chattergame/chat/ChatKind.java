package com.chattergame.chat;

/**
 * Тип чата (`REQUIREMENTS §7`). Словарь объявлен целиком, хотя `E04` работает только с
 * {@link #LOCATION}: значение колонки `chat.kind` — это данные, которые уже пишет и читает
 * БД, и частичное перечисление уронило бы чтение на первой же строке чужого типа.
 *
 * <p>Поведение типов появляется вместе со своим этапом: радио и шёпот — `E11`, личный чат
 * с мастером — `E11`, финальное обсуждение — завершение игры.
 */
public enum ChatKind {

    /** Место в графе (`REQUIREMENTS §7.1`). Предмет `E04`. */
    LOCATION,

    /** Чат связи (`REQUIREMENTS §7.2`). */
    RADIO,

    /** Личный чат игрока с мастером (`REQUIREMENTS §7.3`, `D-037`). */
    MASTER_DM,

    /** Многосторонний приватный канал (`REQUIREMENTS §7.4`, `D-038`). */
    WHISPER,

    /** Чат финального обсуждения (`REQUIREMENTS §7.5`). */
    FINAL
}
