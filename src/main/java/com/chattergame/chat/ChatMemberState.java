package com.chattergame.chat;

/**
 * Состояние участия в чате, который не является локацией (`REQUIREMENTS §7.2`–§7.5).
 *
 * <p>`INVITED` — приглашение без согласия: шёпот создаётся приглашением и живёт по согласию
 * участников (`D-038`), поэтому «приглашён» и «внутри» — разные состояния, а не одно.
 * Радиочат и финальное обсуждение согласия не требуют: список задаёт мастер, и его участник
 * получает {@link #JOINED} сразу.
 *
 * <p>`DECLINED` и `LEFT` различаются затем, чтобы отказ от приглашения не читался как выход
 * из уже состоявшегося разговора: и то и другое — конец участия, но повод разный.
 */
public enum ChatMemberState {

    /** Приглашён, согласие не дано: в чат не пускает и его лента не адресуется. */
    INVITED,

    /** Внутри: читает и пишет по правилам типа чата. */
    JOINED,

    /** Приглашение отклонено. */
    DECLINED,

    /** Вышел или закрыт мастером. */
    LEFT;

    /** Участие живое: по нему адресуется лента и пускается запись. */
    public boolean active() {
        return this == INVITED || this == JOINED;
    }
}
