package com.chattergame.game;

import org.springframework.stereotype.Component;

import java.util.List;
import java.util.UUID;

/**
 * Валидация готовности `DRAFT → READY` (`REQUIREMENTS §20`, `D-009`).
 *
 * <p>На `E03` это каркас: проверки по персонажам, размещению, предметам и переходам
 * опираются на таблицы, которых ещё нет, и включаются вместе со своими этапами
 * (`E04`, `E06`, `E07`). Роль каркаса не декоративная — он фиксирует две вещи, от которых
 * зависит поведение: разделение замечаний на блокирующие и предупреждающие и тот факт, что
 * готовность с предупреждениями разрешена. Когда придут настоящие проверки, изменится тело,
 * а не контракт.
 *
 * <p>Возвращаемое значение не бросает исключение: отчёт нужно показать мастеру целиком,
 * чтобы он видел все замечания сразу, а не по одному за запрос.
 */
@Component
public class ReadinessValidation {

    /**
     * Проверки готовности для игры.
     *
     * <p>Пока возвращается пустой отчёт: на `E03` в игре не может существовать ни одного
     * персонажа, предмета или перехода, поэтому любое найденное замечание было бы выдумано.
     * Место проверок помечено, чтобы их отсутствие не выглядело забывчивостью.
     */
    public ReadinessReport validate(UUID gameId) {
        // TODO(E04/E06/E07): персонаж без размещения, предмет вне хранилища, переход
        // в несуществующую локацию, радиочат менее чем с двумя участниками — блокирующие;
        // локация без описания, персонаж без портрета, недостижимые локации, NPC вне
        // хранилищ и локаций — предупреждающие.
        return ReadinessReport.ok();
    }

    /** Готовность возможна и при предупреждениях: флаг остаётся за мастером (`REQUIREMENTS §20`). */
    public boolean blocksReady(ReadinessReport report) {
        return !report.canBecomeReady();
    }

    public List<ReadinessReport.Finding> all(ReadinessReport report) {
        return java.util.stream.Stream.concat(report.blocking().stream(), report.warning().stream())
                .toList();
    }
}
