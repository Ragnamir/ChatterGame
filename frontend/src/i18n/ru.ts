export type MessageKey = keyof typeof ru;

/** Подстановка `{name}` без экранирования: значения приходят из словаря или данных. */
export function translate(
  key: MessageKey,
  vars?: Readonly<Record<string, string | number>>,
): string {
  const template: string = ru[key];
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

export function hasMessageKey(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(ru, key);
}

export function errorMessage(code: string | null | undefined): string {
  const known = code ? `errors.${code}` : '';
  return known in ru ? translate(known as MessageKey) : translate('errors.generic');
}
